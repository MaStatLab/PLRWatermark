#!/usr/bin/env python3
"""Full-prefix detection curves for the temperature-matched regeneration.

Both arms of every cell here were generated by
:mod:`generate_temperature_matched` at a *common* temperature, so the entropy
confound that contaminates the released pair cannot operate.  This command
recomputes each rule at every prefix length rather than at the four horizons
:mod:`analyse_temperature_matched` reports, and writes

* ``temperature_prefix_curves.csv`` -- every (model, temperature, rule, prefix)
  cell with its Type I and Type II rate and the binomial MCSE of each;
* ``prefix_curves_matched_<model>.pdf`` -- one temperature panel per facet,
  Type II against prefix length;
* ``temperature_sweep_matched.pdf`` -- Type II against temperature at a fixed
  horizon, which is where the discriminating region is legible.

Calibration.  This describes what the code does now; it used to say split-half,
which the code stopped doing.  Type II uses a 5% cutoff taken at each prefix from
the WHOLE unwatermarked arm, without using watermarked scores. The arms remain
paired by prompt; this is not a claim of statistical independence. In the
absence of ties at the cutoff, rules have the same realised calibration size.
With a split-half cutoff from 250 calibration documents the realised level has
standard deviation about .02, which induces a Type II standard deviation near .03,
larger than the differences between the leading rules.  Type I is cross-fitted
over ``CROSS_FIT_FOLDS`` folds instead, so it uses every document without being
calibrated on the one it scores.  The split-half spread is still recorded, as the
quantity the earlier design was drawing from.

No model weights or GPU are used; this reads the generated ``.npz`` arrays.
"""

